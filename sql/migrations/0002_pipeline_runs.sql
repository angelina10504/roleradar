-- 0002 pipeline_runs
--
-- One row per n8n execution of the ingestion workflow. Written by the workflow
-- itself: inserted as 'running' by its first node, closed as 'completed' by its
-- last. The Error Trigger workflow closes it as 'failed'.
--
-- This is the one table in the warehouse that is updated. It is operational
-- state about a run, not an observation of a posting, so decision (a) in
-- CLAUDE.md does not apply to it. jobs_extracted stays append-only.
--
-- A row left 'running' means the execution died without the Error Trigger
-- firing, for example the container was killed. Nothing rewrites that row. The
-- API reports it as abandoned once it is old enough.

CREATE TABLE public.pipeline_runs (
    -- Generated by the database, so the workflow needs no UUID library and the
    -- start node gets the id back from the insert.
    run_id            uuid NOT NULL DEFAULT gen_random_uuid(),

    -- n8n's own id for the execution. This is how an Error Trigger row finds
    -- its run. Deliberately not unique: n8n numbers executions from 1 again if
    -- its volume is recreated, and a unique key here would then reject the
    -- start insert and block every run.
    n8n_execution_id  text,

    started_at        timestamp with time zone NOT NULL DEFAULT now(),
    completed_at      timestamp with time zone,
    status            text NOT NULL DEFAULT 'running',

    -- fetched: postings Remotive returned. processed: items sent to the model,
    -- after the Limit node. accepted and rejected: rows the validator routed
    -- to jobs_extracted and dead_letter_log. NULL until the run closes.
    fetched_count     integer,
    processed_count   integer,
    accepted_count    integer,
    rejected_count    integer,

    -- Set by the Error Trigger workflow on a failed run. No CHECK on the
    -- category on purpose: a typo in a canvas expression must not make the
    -- error insert fail, because then the error is lost. The API maps anything
    -- it does not recognise to 'unknown'.
    error_category    text,
    error_message     text,

    CONSTRAINT pipeline_runs_pkey PRIMARY KEY (run_id),
    CONSTRAINT pipeline_runs_status_check
        CHECK (status IN ('running', 'completed', 'failed')),
    -- running means open, and only running means open.
    CONSTRAINT pipeline_runs_open_iff_running_check
        CHECK ((status = 'running') = (completed_at IS NULL)),
    CONSTRAINT pipeline_runs_completed_after_started_check
        CHECK (completed_at IS NULL OR completed_at >= started_at),
    CONSTRAINT pipeline_runs_counts_non_negative_check
        CHECK (COALESCE(fetched_count, 0)   >= 0
           AND COALESCE(processed_count, 0) >= 0
           AND COALESCE(accepted_count, 0)  >= 0
           AND COALESCE(rejected_count, 0)  >= 0),
    -- Every processed item is routed to exactly one of the two tables.
    CONSTRAINT pipeline_runs_counts_add_up_check
        CHECK (processed_count IS NULL
            OR accepted_count IS NULL
            OR rejected_count IS NULL
            OR accepted_count + rejected_count = processed_count)
);

CREATE INDEX pipeline_runs_started_at_idx
    ON public.pipeline_runs (started_at DESC);

CREATE INDEX pipeline_runs_n8n_execution_id_idx
    ON public.pipeline_runs (n8n_execution_id);
